/** "SA" → "KSA"; unknown/territory → the ISO code itself; empty → null. */
export function countryCode(iso2) {
  if (!iso2 || !/^[A-Za-z]{2}$/.test(iso2)) return null
  const code = iso2.toUpperCase()
  return IOC[code] || code
}

/** "SA" → 🇸🇦 (regional-indicator flag; systems without flag glyphs show the two letters). */
export function flagEmoji(iso2) {
  if (!iso2 || !/^[A-Za-z]{2}$/.test(iso2)) return ''
  return String.fromCodePoint(
    ...iso2
      .toUpperCase()
      .split('')
      .map((c) => 0x1f1e6 + c.charCodeAt(0) - 65),
  )
}
