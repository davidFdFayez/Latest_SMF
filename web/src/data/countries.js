export const COUNTRIES = RAW.map(([code, ar, en, dial]) => ({ code, ar, en, dial }));

/** Sorted for a picker in the requested language, Saudi Arabia pinned first. */
export function countriesFor(lang) {
  const collator = new Intl.Collator(lang === 'ar' ? 'ar' : 'en');
  const rest = COUNTRIES.filter((c) => c.code !== 'SA').sort((a, b) =>
    collator.compare(lang === 'ar' ? a.ar : a.en, lang === 'ar' ? b.ar : b.en),
  );
  return [COUNTRIES.find((c) => c.code === 'SA'), ...rest];
}

export const COUNTRY_BY_CODE = new Map(COUNTRIES.map((c) => [c.code, c]));

/** Dial codes, longest first, so +1268 wins over +1 when parsing a number. */
export const DIAL_CODES = [...new Set(COUNTRIES.map((c) => c.dial))].sort(
  (a, b) => b.length - a.length || Number(a) - Number(b),
);

